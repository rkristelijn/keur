#!/usr/bin/env bash
# gen-golden.sh — regenerate the golden-output snapshot (<name>.out.txt) for
# every demo tape, so a demo's expected result lives verifiably in the repo
# (ADR-047). Companion to run.sh: run.sh executes a tape's commands; this wraps
# that output into a committed snapshot CI can later diff against.
#
#   ./gen-golden.sh            regenerate all <name>.out.txt (skips TEMPLATE)
#   ./gen-golden.sh <tape>...  regenerate only the named tape(s)
#   ./gen-golden.sh --check    regenerate to a temp file and FAIL if any
#                              committed .out.txt is stale (for CI)
#
# Each .out.txt carries a snapshot header (date + caveats): the demo repos are
# still bare, so output includes repo-hygiene findings around the targeted one,
# and run.sh only replays `Type "..."` lines so it ~= (not == ) the GIF.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd -P)"
cd "$HERE"

CHECK=0
case "${1:-}" in
  --check) CHECK=1; shift ;;
esac

# Tapes to SKIP for golden output: TEMPLATE (not a demo) + the install-* demos.
# The install demos are network/release-dependent and NOT reproducible via
# run.sh: `npx keur` 404s until the npm publish, install.sh leaks the renderer's
# global ~/.config/keur version, and the npm error log embeds a PII path. Their
# correctness is shown by the rendered GIF against the live release, not a
# golden snapshot. Verify them with `vhs` + a frame check, not here.
skip_tape() {
  case "$1" in
    TEMPLATE.tape|install-*.tape) return 0 ;;
    *) return 1 ;;
  esac
}

# Which tapes: args if given, else every *.tape that is not skipped.
if [[ $# -gt 0 ]]; then
  tapes=("$@")
else
  tapes=()
  for t in *.tape; do
    skip_tape "$t" && continue
    tapes+=("$t")
  done
fi

# Write the golden snapshot for one tape to stdout (header + ANSI-stripped run).
emit() {
  local tape="$1" name="${1%.tape}"
  printf '# GOLDEN OUTPUT SNAPSHOT — %s\n' "$tape"
  printf '# Generated by docs/demo/gen-golden.sh via run.sh (ANSI-stripped).\n'
  printf '# CAVEATS:\n'
  printf '#  1. Snapshot of the CURRENT output — demo repos are bare, so keur\n'
  printf '#     adds repo-hygiene findings (KEUR-DOC/PROJ/CFG) around the one the\n'
  printf '#     demo targets. Regenerate after a tape/sandbox cleanup.\n'
  printf '#  2. run.sh replays only `Type "..."` lines; complex escapes may\n'
  printf '#     differ slightly from the rendered GIF. This is ~= the GIF.\n'
  printf '# ---------------------------------------------------------------------------\n'
  bash run.sh "$tape" 2>&1 | sed 's/\x1b\[[0-9;]*m//g; s/\x1b\[[HJ]//g'
}

rc=0
for tape in "${tapes[@]}"; do
  [[ -f "$tape" ]] || { echo "gen-golden: no such tape: $tape" >&2; rc=2; continue; }
  if skip_tape "$tape"; then
    echo "gen-golden: skip $tape (not a golden-output demo — see header)"
    continue
  fi
  name="${tape%.tape}"
  out="${name}.out.txt"
  if [[ "$CHECK" -eq 1 ]]; then
    tmp="$(mktemp)"
    emit "$tape" > "$tmp"
    if ! diff -q "$out" "$tmp" >/dev/null 2>&1; then
      echo "gen-golden: STALE — $out differs from a fresh run (run ./gen-golden.sh)" >&2
      rc=1
    else
      echo "gen-golden: ok — $out current"
    fi
    rm -f "$tmp"
  else
    emit "$tape" > "$out"
    echo "gen-golden: wrote $out"
  fi
done
exit "$rc"
