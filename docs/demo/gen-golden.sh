#!/usr/bin/env bash
# gen-golden.sh — regenerate the golden-output snapshot (<name>.out.txt) for
# every demo tape by running its commands in a shell (via run.sh) and capturing
# the output (ADR-047). Companion to run.sh; a committed snapshot CI can diff.
#
#   ./gen-golden.sh            regenerate all <name>.out.txt (skips below)
#   ./gen-golden.sh <tape>...  regenerate only the named tape(s)
#   ./gen-golden.sh --check    regenerate to a temp file and FAIL if a committed
#                              .out.txt is stale (for CI)
#
# Scope note (deliberate, after trying the alternative): the snapshot comes from
# run.sh — the tape's commands executed in a shell — NOT from a vhs render. vhs
# is a demo recorder, not a test harness; dumping its animation frames as a
# golden file is fragile and nobody does it. The ONE thing run.sh misses is a
# pure *render* bug (e.g. a backtick-printf whose \n shows literally in the GIF
# but runs fine in a shell). That is a tape-authoring bug, fixed at the source
# (use a heredoc, not backtick-printf) + guarded by a lint — not by sourcing the
# golden output from vhs.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd -P)"
cd "$HERE"

CHECK=0
case "${1:-}" in
  --check) CHECK=1; shift ;;
esac

# SKIP: TEMPLATE (not a demo) + install-* (network/release-dependent, not
# reproducible here — verified by the rendered GIF against the live release).
skip_tape() {
  case "$1" in
    TEMPLATE.tape|install-*.tape) return 0 ;;
    *) return 1 ;;
  esac
}

if [[ $# -gt 0 ]]; then
  tapes=("$@")
else
  tapes=()
  for t in *.tape; do
    skip_tape "$t" && continue
    tapes+=("$t")
  done
fi

# Golden snapshot for one tape: header + ANSI-stripped run.sh output.
emit() {
  local tape="$1"
  printf '# GOLDEN OUTPUT SNAPSHOT — %s\n' "$tape"
  printf '# Generated by docs/demo/gen-golden.sh via run.sh (ANSI-stripped).\n'
  printf '# CAVEATS:\n'
  printf '#  1. Snapshot of the CURRENT output — demo repos are bare, so keur\n'
  printf '#     adds repo-hygiene findings (KEUR-DOC/PROJ/CFG) around the one the\n'
  printf '#     demo targets. Regenerate after a tape/sandbox cleanup.\n'
  printf '#  2. run.sh runs the tape commands in a shell, so it does NOT catch a\n'
  printf '#     pure render bug (e.g. literal \\n from a backtick-printf). That is\n'
  printf '#     a tape bug — fix it in the tape (heredoc), not here.\n'
  printf '# ---------------------------------------------------------------------------\n'
  bash run.sh "$tape" 2>&1 | sed 's/\x1b\[[0-9;]*m//g; s/\x1b\[[HJ]//g'
}

rc=0
for tape in "${tapes[@]}"; do
  [[ -f "$tape" ]] || { echo "gen-golden: no such tape: $tape" >&2; rc=2; continue; }
  if skip_tape "$tape"; then
    echo "gen-golden: skip $tape (not a golden-output demo — see header)"
    continue
  fi
  name="${tape%.tape}"
  out="${name}.out.txt"
  if [[ "$CHECK" -eq 1 ]]; then
    tmp="$(mktemp)"
    emit "$tape" > "$tmp"
    if ! diff -q "$out" "$tmp" >/dev/null 2>&1; then
      echo "gen-golden: STALE — $out differs from a fresh run (run ./gen-golden.sh)" >&2
      rc=1
    else
      echo "gen-golden: ok — $out current"
    fi
    rm -f "$tmp"
  else
    emit "$tape" > "$out"
    echo "gen-golden: wrote $out"
  fi
done
exit "$rc"
