#!/usr/bin/env bash
# gen-golden.sh — regenerate the golden-output snapshot (<name>.out.txt) for
# every demo tape by running its commands in a shell (via run.sh) and capturing
# the output (ADR-047). Companion to run.sh; a committed snapshot CI can diff.
#
#   ./gen-golden.sh            regenerate all <name>.out.txt (skips below)
#   ./gen-golden.sh <tape>...  regenerate only the named tape(s)
#   ./gen-golden.sh --check    regenerate to a temp file and FAIL if a committed
#                              .out.txt is stale (for CI)
#
# Scope note (deliberate, after trying the alternative): the snapshot comes from
# run.sh — the tape's commands executed in a shell — NOT from a vhs render. vhs
# is a demo recorder, not a test harness; dumping its animation frames as a
# golden file is fragile and nobody does it. The ONE thing run.sh misses is a
# pure *render* bug (e.g. a backtick-printf whose \n shows literally in the GIF
# but runs fine in a shell). That is a tape-authoring bug, fixed at the source
# (use a heredoc, not backtick-printf) + guarded by a lint — not by sourcing the
# golden output from vhs.
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd -P)"
cd "$HERE"

CHECK=0
case "${1:-}" in
  --check) CHECK=1; shift ;;
esac

# SKIP: TEMPLATE (not a demo) + install-* (network/release-dependent, not
# reproducible here — verified by the rendered GIF against the live release).
skip_tape() {
  case "$1" in
    TEMPLATE.tape|install-*.tape) return 0 ;;
    *) return 1 ;;
  esac
}

if [[ $# -gt 0 ]]; then
  tapes=("$@")
else
  tapes=()
  for t in *.tape; do
    tapes+=("$t")   # skipped tapes still get the isolation check below
  done
fi

# Golden snapshot for one tape: header + ANSI-stripped run.sh output.
emit() {
  local tape="$1"
  printf '# GOLDEN OUTPUT SNAPSHOT — %s\n' "$tape"
  printf '# Generated by docs/demo/gen-golden.sh via run.sh (ANSI-stripped).\n'
  printf '# CAVEATS:\n'
  printf '#  1. Snapshot of the CURRENT output — demo repos are bare, so keur\n'
  printf '#     adds repo-hygiene findings (KEUR-DOC/PROJ/CFG) around the one the\n'
  printf '#     demo targets. Regenerate after a tape/sandbox cleanup.\n'
  printf '#  2. run.sh runs the tape commands in a shell, so it does NOT catch a\n'
  printf '#     pure render bug (e.g. literal \\n from a backtick-printf). That is\n'
  printf '#     a tape bug — fix it in the tape (heredoc), not here.\n'
  printf '# ---------------------------------------------------------------------------\n'
  bash run.sh "$tape" 2>&1 | sed 's/\x1b\[[0-9;]*m//g; s/\x1b\[[HJ]//g'
}

# --- Content checks: a snapshot that merely exists proves nothing -------------
# A golden file can be perfectly "current" and still record a failed run (a
# vanished sandbox dir, a rule that never matched). Two cheap guards, applied
# when generating AND when checking:
#   1. no shell/run error markers in the output;
#   2. every id the tape promises with `# @shows <ID>...` has a real VERDICT
#      line (a JSON finding or a "BLOCK|warn <ID> |" line), not just a mention in
#      an explainer, which is how a rule that never fired used to slip through.
RUN_ERRORS='no such file or directory|getcwd|cannot access parent|unable to read current working|shell-init|command not found|vhs render produced no'

shown_ids() {
  sed -nE 's/^#[[:space:]]*@shows[[:space:]]+(.*)$/\1/p' "$1" | head -1
}

# Print a problem per line for a snapshot file; print nothing when it is sound.
snapshot_problems() {
  local tape="$1" file="$2" id
  if grep -qiE "$RUN_ERRORS" "$file"; then
    echo "contains run errors ($(grep -ciE "$RUN_ERRORS" "$file") line(s)): a failed run, not a demo"
  fi
  for id in $(shown_ids "$tape"); do
    if ! grep -qE "\"rule\":\"$id\"|^[[:space:]]*(BLOCK|block|warn|WARN|info|advisory)[[:space:]]+$id([[:space:]]|$)" "$file"; then
      echo "no verdict line for @shows $id: the demo does not show what it claims"
    fi
  done
}

# 3. a tape works only in its OWN /tmp/demo-<name> dirs. Tapes that shared one
#    /tmp/demo removed each other's working dir when rendered together, which
#    recorded "no such file or directory" into a GIF (pii-in-code, dutch-in-docs).
tape_isolation_problems() {
  local tape="$1" name
  name="$(basename "$tape" .tape)"
  [[ "$name" == "TEMPLATE" ]] && name="NAME"
  grep -oE '/tmp/demo[-A-Za-z0-9_]*' "$tape" | sort -u | while read -r dir; do
    case "$dir" in
      "/tmp/demo-$name"|"/tmp/demo-$name-"*) ;;
      *) echo "uses shared dir $dir: use /tmp/demo-$name (each tape owns its dirs)" ;;
    esac
  done
}

# 4. a tape that runs the gate must WAIT for its verdict before typing on. With
#    a fixed Sleep, a slow render typed the next line into keur's output (seen in
#    dutch-in-docs). `Wait /❯/` waits until the prompt is back on the last line,
#    i.e. the command finished, however long its output is.
tape_wait_problems() {
  awk '
    /^Type .*(keur check|git commit)/ { pending = NR; next }
    pending && /^Wait/ { pending = 0; next }
    pending && /^Type / { printf "line %d runs the gate without a Wait for its verdict; ", pending; pending = 0 }
    END { if (pending) printf "line %d runs the gate without a Wait for its verdict; ", pending }
  ' "$1"
}

rc=0
for tape in "${tapes[@]}"; do
  [[ -f "$tape" ]] || { echo "gen-golden: no such tape: $tape" >&2; rc=2; continue; }
  waits="$(tape_wait_problems "$tape")"
  if [[ -n "$waits" ]]; then
    echo "gen-golden: BAD — $tape: ${waits%; }" >&2
    rc=1
  fi
  isolation="$(tape_isolation_problems "$tape")"
  if [[ -n "$isolation" ]]; then
    echo "gen-golden: BAD — $tape: ${isolation//$'\n'/; }" >&2
    rc=1
  fi
  if skip_tape "$tape"; then
    echo "gen-golden: skip $tape (not a golden-output demo — see header)"
    continue
  fi
  name="${tape%.tape}"
  out="${name}.out.txt"
  if [[ "$CHECK" -eq 1 ]]; then
    tmp="$(mktemp)"
    if ! emit "$tape" > "$tmp"; then
      echo "gen-golden: BAD — $out: capture failed (run.sh or sed exited non-zero)" >&2
      rc=1; rm -f "$tmp"; continue
    fi
    if ! diff -q "$out" "$tmp" >/dev/null 2>&1; then
      echo "gen-golden: STALE — $out differs from a fresh run (run ./gen-golden.sh)" >&2
      rc=1
    else
      echo "gen-golden: ok — $out current"
    fi
    problems="$(snapshot_problems "$tape" "$tmp")"
    if [[ -n "$problems" ]]; then
      echo "gen-golden: BAD — $out: ${problems//$'\n'/; }" >&2
      rc=1
    fi
    rm -f "$tmp"
  else
    if ! emit "$tape" > "$out.tmp"; then
      echo "gen-golden: BAD — $out: capture failed (run.sh or sed exited non-zero); kept the old snapshot" >&2
      rc=1; rm -f "$out.tmp"; continue
    fi
    mv "$out.tmp" "$out"
    echo "gen-golden: wrote $out"
    problems="$(snapshot_problems "$tape" "$out")"
    if [[ -n "$problems" ]]; then
      echo "gen-golden: BAD — $out: ${problems//$'\n'/; }" >&2
      rc=1
    fi
  fi
done
exit "$rc"
