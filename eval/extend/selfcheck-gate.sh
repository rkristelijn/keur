#!/usr/bin/env bash
set -uo pipefail

# selfcheck-gate.sh — run keur over every draft in the review queue and check it
# against its own KEUR-EXPECT annotation:
#   - positive draft: the expected rule MUST fire,
#   - negative draft: nothing (esp. the KEUR-EXPECT-NOT rule) may fire.
#
# This is the cheap, automatic gate between generation and human review. Drafts
# that pass are recorded in review-queue/.gate-pass.jsonl (ready for promotion);
# drafts that fail are recorded in review-queue/.gate-fail.jsonl with the reason,
# so the generator can offer them to Ollama for a self-correct (inside the loop).
# Nothing is promoted or committed here — that is a human step, outside the loop.
#
# `recall`-tier drafts (KEUR-TIER: recall) name a reserved rule keur cannot fire
# yet; their positive is expected NOT to fire. The gate records them as
# "recall-gap" (informational), not as a failure.
#
# Usage: selfcheck-gate.sh [--self-correct]
#   --self-correct   after grading, re-run the generator on failed concepts once
#                    (requires Ollama; no-op in this repo without a model)
# Env: KEUR_EVAL, KEUR_BIN, KEUR_RULES_DIRS

HERE="$(cd "$(dirname "$0")" && pwd -P)"
KEUR_HOME="$(cd "$HERE/../.." && pwd -P)"
KEUR_EVAL="${KEUR_EVAL:-$HOME/git/hub/keur-eval}"
KEUR_BIN="${KEUR_BIN:-$KEUR_HOME/bin/keur}"
export KEUR_RULES_DIRS="${KEUR_RULES_DIRS:-$KEUR_HOME/rules/security}"

QUEUE="$KEUR_EVAL/review-queue"
PASS_LOG="$QUEUE/.gate-pass.jsonl"
FAIL_LOG="$QUEUE/.gate-fail.jsonl"

[ -x "$KEUR_BIN" ] || { echo "keur binary not found: $KEUR_BIN (make build)" >&2; exit 1; }
[ -d "$QUEUE" ] || { echo "no review queue yet: $QUEUE" >&2; exit 0; }

: > "$PASS_LOG"; : > "$FAIL_LOG"

# fired rules for a file, scanned RELATIVE to the corpus root so keur's
# substring exclude_paths (eval/, tests/) do not accidentally match.
fired_rules() {  # $1 = path relative to KEUR_EVAL
  ( cd "$KEUR_EVAL" && "$KEUR_BIN" scan "$1" 2>/dev/null ) \
    | python3 -c "import sys,json;print(' '.join(json.loads(l)['rule'] for l in sys.stdin if l.strip().startswith('{')))"
}

# read an annotation value (first match) from a file head
annot() { grep -m1 "$2" "$1" 2>/dev/null | sed "s/.*$2[[:space:]]*//; s/[[:space:]]*-->.*//"; }

pass=0 fail=0 recall=0
while IFS= read -r abs; do
  rel="${abs#"$KEUR_EVAL"/}"
  base="$(basename "$abs")"
  expect="$(annot "$abs" 'KEUR-EXPECT:')"
  expect_not="$(annot "$abs" 'KEUR-EXPECT-NOT:')"
  tier="$(annot "$abs" 'KEUR-TIER:')"
  fired="$(fired_rules "$rel")"

  reason=""; status=""
  case "$base" in
    *positive*)
      want="${expect%%@*}"; want="${want%% *}"
      if [ "$tier" = "recall" ]; then
        # reserved rule keur cannot fire yet — a documented gap, not a failure.
        status="recall-gap"; reason="recall tier: $want not detectable yet"
      elif printf ' %s ' "$fired" | grep -q " $want "; then
        status="pass"; reason="expected $want fired"
      else
        status="fail"; reason="expected $want did NOT fire (fired: ${fired:-none})"
      fi ;;
    *negative*)
      if [ -z "$fired" ]; then
        status="pass"; reason="stayed quiet (no rule fired)"
      elif [ -n "$expect_not" ] && printf ' %s ' "$fired" | grep -q " $expect_not "; then
        status="fail"; reason="$expect_not fired but must not (false positive)"
      else
        status="fail"; reason="unexpected rule fired: $fired"
      fi ;;
    *) continue ;;
  esac

  rec=$(python3 -c "import json,sys;print(json.dumps({'path':sys.argv[1],'status':sys.argv[2],'reason':sys.argv[3],'fired':sys.argv[4].split()}))" \
        "$rel" "$status" "$reason" "$fired")
  case "$status" in
    pass)       echo "$rec" >> "$PASS_LOG"; pass=$((pass+1));  printf "  PASS   %s  (%s)\n" "$rel" "$reason";;
    recall-gap) echo "$rec" >> "$PASS_LOG"; recall=$((recall+1)); printf "  RECALL %s  (%s)\n" "$rel" "$reason";;
    fail)       echo "$rec" >> "$FAIL_LOG"; fail=$((fail+1));  printf "  FAIL   %s  (%s)\n" "$rel" "$reason";;
  esac
done < <(find "$QUEUE" -type f \( -name '*positive*' -o -name '*negative*' \) | sort)

echo ""
echo "  gate: $pass pass, $recall recall-gap, $fail fail"
echo "  pass log: $PASS_LOG"
echo "  fail log: $FAIL_LOG"

if [ "${1:-}" = "--self-correct" ] && [ "$fail" -gt 0 ]; then
  echo ""
  echo "  --self-correct: failed drafts should be regenerated by Ollama."
  echo "  (concepts to retry are in $FAIL_LOG; wire this to gen-from-knowledge"
  echo "   once a model is available. No-op here without Ollama.)"
fi

# Gate exit is informational: failures do not block (they route to self-correct).
exit 0
