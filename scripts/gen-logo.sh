#!/usr/bin/env bash
# gen-logo.sh — bake the KEUR DOOM logo into C++ as responsive braille assets.
#
# Offline generator (ADR-002: no runtime image lib in the gate). Converts the
# logo PNG to coloured + mono braille at four terminal-width buckets and writes
# render/logo_generated.cpp with the strings baked in — the same "generate once,
# compile in" pattern as scripts/gen-catalog.sh.
#
# Requires: ffmpeg (PNG -> raw RGBA), node (the braille converter). Both are
# build-time only; the resulting binary needs neither.
#
# Usage: scripts/gen-logo.sh <out.cpp> <logo.png> [converter.js]
set -euo pipefail

OUT="${1:?usage: gen-logo.sh <out.cpp> <logo.png> [converter.js]}"
LOGO="${2:?need logo png}"
CONV="${3:-$(cd "$(dirname "$0")/.." && pwd -P)/.tmp/img2braille.js}"

command -v ffmpeg >/dev/null || { echo "gen-logo: ffmpeg not found" >&2; exit 1; }
command -v node   >/dev/null || { echo "gen-logo: node not found" >&2; exit 1; }
[[ -f "$LOGO" ]] || { echo "gen-logo: logo not found: $LOGO" >&2; exit 1; }
[[ -f "$CONV" ]] || { echo "gen-logo: converter not found: $CONV" >&2; exit 1; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# Buckets: name, braille-cols, threshold. Lower threshold = fuller, more legible.
# See docs/design/doom-level-select.md for the verified table.
BUCKETS=("sm 48 120" "md 72 135" "lg 96 140" "xl 128 150")

# Render source: scale wide enough that the smallest bucket still samples detail.
SRCW=384
ffmpeg -y -loglevel error -i "$LOGO" -vf "scale=${SRCW}:-1" -pix_fmt rgba -f rawvideo "$TMP/logo.rgba"
SRCH=$(( $(stat -f%z "$TMP/logo.rgba" 2>/dev/null || stat -c%s "$TMP/logo.rgba") / (SRCW * 4) ))

# Trim blank braille rows top/bottom (ANSI-aware).
trim() {
  awk 'BEGIN{s=0}{ln[NR]=$0;g=$0;gsub(/\033\[[0-9;]*m/,"",g);
    if(g ~ /[^ \342\240\200]/){if(!s){f=NR;s=1} l=NR}} END{for(i=f;i<=l;i++)print ln[i]}'
}

# C++ string-escape a line (backslash, quote, and \x1b -> \033).
cpp_escape() {
  # Escape backslash and quote. Emit ESC as the bounded hex form \x1b wrapped so
  # a following hex digit cannot extend the escape: "\x1b" "..." (string break).
  # Sonar flags octal \033 and open-ended \x1b<hexdigit> as unbounded escapes.
  sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e $'s/\x1b/\\\\x1b""/g'
}

emit_asset() {
  local var="$1" file="$2"
  printf 'const char* const %s =\n' "$var" >> "$OUT"
  while IFS= read -r line; do
    printf '    "%s\\n"\n' "$(printf '%s' "$line" | cpp_escape)" >> "$OUT"
  done < "$file"
  printf '    ;\n\n' >> "$OUT"
}

{
  echo '// GENERATED by scripts/gen-logo.sh — do not edit by hand.'
  echo '// KEUR DOOM logo as responsive braille (see docs/design/doom-level-select.md).'
  echo '#include "render/logo.h"'
  echo
  echo 'namespace keur::render {'
  echo
} > "$OUT"

for b in "${BUCKETS[@]}"; do
  set -- $b; NAME=$1; COLS=$2; T=$3
  node "$CONV" "$TMP/logo.rgba" "$SRCW" "$SRCH" --cols "$COLS" --invert --threshold "$T" --color | trim > "$TMP/$NAME.color"
  node "$CONV" "$TMP/logo.rgba" "$SRCW" "$SRCH" --cols "$COLS" --invert --threshold "$T"         | trim > "$TMP/$NAME.mono"
  emit_asset "k_logo_${NAME}_color" "$TMP/$NAME.color"
  emit_asset "k_logo_${NAME}_mono"  "$TMP/$NAME.mono"
done

{
  echo 'const char* keur_logo(Bucket b, bool color) {'
  echo '    switch (b) {'
  echo '        case Bucket::Sm: return color ? k_logo_sm_color : k_logo_sm_mono;'
  echo '        case Bucket::Md: return color ? k_logo_md_color : k_logo_md_mono;'
  echo '        case Bucket::Lg: return color ? k_logo_lg_color : k_logo_lg_mono;'
  echo '        case Bucket::Xl: return color ? k_logo_xl_color : k_logo_xl_mono;'
  echo '    }'
  echo '    return k_logo_md_mono;'
  echo '}'
  echo
  echo '}  // namespace keur::render'
} >> "$OUT"

echo "gen-logo: wrote $(grep -c '"' "$OUT") lines to $OUT"
