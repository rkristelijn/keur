#!/usr/bin/env bash
# gen-adr-index.sh — regenerate docs/adr/README.md from the ADR files themselves.
#
# The index is DERIVED, never hand-maintained: a hand index goes stale the moment
# someone adds an ADR and forgets the index (exactly the stale-snapshot class of
# bug ADR-051 is about). This reads every docs/adr/ADR-*.md, extracts its title
# and status, and emits the numbered table. Run it after adding/renaming an ADR;
# CI can run it with --check to fail if the committed index is out of date.
#
# Title : the first markdown H1 ("# ADR-NNN — ...").
# Status: the first "Status" value, whether written as "**Status**: accepted",
#         "Status: accepted", or a "## Status" section with the value on the
#         next non-blank line. Normalised to a short token for the table.
#
# Usage:  scripts/gen-adr-index.sh [--check]
#   (no arg)  rewrite docs/adr/README.md in place
#   --check   print nothing and exit 1 if README.md differs from freshly
#             generated output (for CI); exit 0 if in sync.
#
# Portable: POSIX tools only (ERE grep, no realpath) — macOS + Linux/WSL.
set -euo pipefail

# ADR titles carry em-dashes / accented backticks. Force a UTF-8 locale the host
# has, so sed/awk do not split multibyte chars (same guard as gen-catalog.sh).
if ! locale 2>/dev/null | grep -qiE 'UTF.?8'; then
  if locale -a 2>/dev/null | grep -qiE '^C\.utf.?8$'; then
    export LC_ALL=C.UTF-8
  else export LC_ALL=en_US.UTF-8; fi
fi

# Resolve the adr dir relative to this script (no realpath dependency).
script_dir="$(cd "$(dirname "$0")" && pwd -P)"
adr_dir="$(cd "$script_dir/../docs/adr" && pwd -P)"
readme="$adr_dir/README.md"

mode="write"
[[ "${1:-}" == "--check" ]] && mode="check"

# Extract the H1 title text after "# " (first line of the file).
adr_title() {
  sed -n '1s/^# *//p' "$1"
}

# Extract a normalised status token. Handles three notations; returns one of
# accepted | proposed | parked | <verbatim-first-word-lowercased>.
adr_status() {
  local f="$1" raw
  # 1) inline status, any of: "**Status**: X", "**Status:** X", "Status: X".
  #    Strip the markdown bold markers first, then take the value after "Status:".
  #    Stop at the first · separator (date/coverage follow it).
  raw="$(sed -n 's/\*\*//g; s/^[[:space:]]*[Ss]tatus:[[:space:]]*//p' "$f" \
         | head -1 | sed 's/·.*//')"
  # 2) "## Status" section: value on the next non-blank line
  if [[ -z "$raw" ]]; then
    raw="$(awk 'tolower($0) ~ /^## *status/{getline; while($0 ~ /^[[:space:]]*$/) getline; print; exit}' "$f" \
           | sed 's/·.*//')"
  fi
  # Normalise: lowercase, trim, collapse to a known token when possible.
  raw="$(printf '%s' "$raw" | tr '[:upper:]' '[:lower:]' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
  case "$raw" in
    *parked*)   echo "parked" ;;
    *accepted*proposed*|*proposed*accepted*) echo "accepted / proposed" ;;
    *accepted*) echo "accepted" ;;
    *proposed*) echo "proposed" ;;
    "")         echo "—" ;;
    *)          echo "$raw" ;;
  esac
}

# Build the generated document into a temp file, then write or diff.
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

{
  cat <<'HEADER'
<!-- GENERATED by scripts/gen-adr-index.sh — do not edit by hand.
     Re-run after adding or renaming an ADR. CI checks it with --check. -->
# Architecture Decision Records (ADRs)

The *why* behind keur's design. Each ADR captures one decision — its context,
the choice made, and the consequences — so the reasoning survives the code.

- **Format**: `ADR-NNN-short-slug.md`, numbered in decision order.
- **Status**: `accepted` (in effect), `proposed` (decided-in-principle, not all
  built), or `parked` (deliberately deferred — captured so it is not re-litigated).
- **Traceability**: ADRs declare an `@id ADR-NNN`; code links back with
  `@implements ADR-NNN` and tests with `@proves ADR-NNN` (ADR-010).

New here? Read **ADR-001** (native RE2 engine), **ADR-002** (single binary),
**ADR-003** (provider/adapter architecture), then **ADR-009** (rules are data,
the engine stays minimal) and **ADR-010** (traceability).

## All ADRs (by number)

| # | Title | Status |
|---|-------|--------|
HEADER

  # One row per ADR, sorted by number. ADR numbers are zero-padded 3-digit
  # (ADR-001..ADR-NNN), so a plain lexicographic sort orders them correctly —
  # no GNU-only version-sort flag needed (portable to BusyBox/macOS).
  for f in $(find "$adr_dir" -name 'ADR-*.md' -type f 2>/dev/null | sort); do
    base="$(basename "$f")"
    num="$(printf '%s' "$base" | sed -n 's/^ADR-\([0-9]*\)-.*/\1/p')"
    title="$(adr_title "$f")"
    # Strip the leading "ADR-NNN — " or "ADR-NNN: " prefix so the title column is clean.
    title="$(printf '%s' "$title" | sed 's/^ADR-[0-9]*[[:space:]]*\([—:-][[:space:]]*\)//')"
    status="$(adr_status "$f")"
    printf '| [%s](%s) | %s | %s |\n' "$num" "$base" "$title" "$status"
  done

  cat <<'FOOTER'

## Adding an ADR

1. Copy the shape of a recent one (title line, an `@id ADR-NNN`, a
   **Status · Date · Coverage · Relates to** line, then
   **Context → Decision → Consequences**).
2. Take the next free number. Link related ADRs both ways.
3. Run `scripts/gen-adr-index.sh` to refresh this index — do not edit it by hand.
FOOTER
} > "$tmp"

if [[ "$mode" == "check" ]]; then
  if ! diff -q "$readme" "$tmp" >/dev/null 2>&1; then
    echo "docs/adr/README.md is out of date — run scripts/gen-adr-index.sh" >&2
    exit 1
  fi
  exit 0
fi

mv "$tmp" "$readme"
trap - EXIT
echo "wrote $readme ($(grep -c '^| \[' "$readme") ADRs)"
